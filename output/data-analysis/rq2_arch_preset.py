import argparse, hashlib, json, os, sys
from pathlib import Path

A = Path('/home/wonmin-kim/AIVC/output/data-analysis/results/rq2_arch')
SCRIPTS = '/home/wonmin-kim/AIVC/vcc2026_data/scripts'
REAL_SHA = {'K562': '7c7a777b1b6afc810dfd83daed9917f863571c6d4b8e458fcd7c726a1ea9951f',
            'HepG2': '4d37d551f82235558e9da8d1f357ea93b85e2be21e403db9ba50ccb67b867e88'}


def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 22), b''):
            h.update(b)
    return h.hexdigest()


def realpanel(line):
    sys.path.insert(0, SCRIPTS)
    import numpy as np, anndata as ad, gc
    import context_forcing_score as C
    sys.path.insert(0, SCRIPTS)
    import b19_sweep2_full_metrics as B
    E = C.E
    out = A / 'real' / line / 'real_disjoint.h5ad'
    if out.exists():
        print(json.dumps(dict(event='realpanel_exists', line=line, sha=sha(out), match=sha(out) == REAL_SHA[line])), flush=True)
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    worker = C.ContextForcingScoreWorker(A / 'real' / 'worker_root')
    data = worker._load_line(line)
    targets0 = json.loads((C.ROOT / 'reports/context_forcing_2026-09-16/protocol.json').read_text())['final_targets'][line]
    delta = np.load(C.ROOT / 'reports/ext_contexts_2026-09-21' / line / 'refit_v2.npy')
    _, audit = C.prepare_delta(delta, targets0, data, 3.); targets = audit['sorted_targets']
    original = ad.read_h5ad(C.KOLF_REAL if line == 'KOLF' else C.RN_MOCK / line / 'panel300/real.h5ad')
    real = B.replace_real_controls(original, data, targets); del original
    truth = E.pseudobulk_bulk_lognorm(real, 'target', bulk_target_sum=E.BULK_TARGET_SUM)
    expected = C._subset_truth(data.real_bulk, targets, data.reference_controls)
    np.testing.assert_array_equal(truth[0], expected[0])
    np.testing.assert_allclose(truth[1], expected[1], rtol=0, atol=1e-12)
    real.write_h5ad(out, compression='gzip'); del real; gc.collect(); worker.close()
    s = sha(out)
    print(json.dumps(dict(event='realpanel_built', line=line, path=str(out), sha=s, reference_sha=REAL_SHA[line],
                          byte_identical=s == REAL_SHA[line], truth_check='pass')), flush=True)


def score(src, line, seed, arms):
    os.environ['EXT_SRC'] = str(Path(src).resolve())
    sys.path.insert(0, SCRIPTS)
    import ext_preset_score as P
    sys.path.insert(0, SCRIPTS)
    bdir = A / 'bundles' / line
    bdir.mkdir(parents=True, exist_ok=True)
    link = bdir / 'bundle'
    if not link.exists():
        link.symlink_to(P.C.ROOT / 'reports/preset_rescore_2026-09-20/bundles' / line / 'bundle')
    P.BUNDLES = A / 'bundles'
    orig = P.real_path
    def real_path(l):
        if l == 'K562':
            p = A / 'real' / 'K562' / 'real_disjoint.h5ad'
            if not p.exists():
                raise FileNotFoundError(f'run realpanel --line K562 first: {p}')
            return p
        return orig(l)
    P.real_path = real_path
    P.ROOT.mkdir(parents=True, exist_ok=True)
    P.phase_run(line, arms, [seed])
    P.phase_score(line, arms, [seed])
    print(json.dumps(dict(event='preset_complete', src=str(src), line=line, seed=seed, arms=arms)), flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['realpanel', 'score'])
    ap.add_argument('--line', required=True)
    ap.add_argument('--src', default='')
    ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--arms', default='')
    a = ap.parse_args()
    if a.phase == 'realpanel':
        realpanel(a.line)
    else:
        score(a.src, a.line, a.seed, [x for x in a.arms.split(',') if x])
